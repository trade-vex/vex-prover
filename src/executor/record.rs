pub type Instructions<F> = Vec<[F; N_INSTRUCTION_FELTS]>;
pub type InstructionFelts<F> = [F; N_INSTRUCTION_FELTS];

/// ExecutionTrace contains Instructions executed by matching engine during the execution
/// There are two types of events:
/// 1. User Events: Events that are generated by the user
///     - Place Order: User places an order
///     - Cancel Order: User cancels an order
///     - Modify Order: User modifies an order
/// 2. System Events: Events that are generated by the system
///     - Order Matched: Two orders are matched
///     - Order Partial Matched: An order is cancelled
///
///
///
/// Each Event corresponds to a Tree Instruction in IndexedMerkleTree
/// These events occur in Buy as well as Sell side, so there are total of 10 Instruction Types
///
/// These Instructions require additional Auxillary Operations to be computed for Constraint Evaluation
/// 1. Add Operations: Add two Field Elements
/// 2. Less Than Operations: Compare two Price pairs, comprising 8 Field Elements each
/// 3. Comparison Operations: Compare two Price, Time pairs
/// 4. Hash Operations: Poseidon Hash Operations
/// 5. Byte Operations: U8 Operations such as and, less than, range check
pub struct ExecutionTrace<F> {
    /// Buy Side Instructions
    /// 1. Place Buy Order
    pub buy_insert_order: Instructions<F>,
    /// 2. Cancel Buy Order
    pub buy_delete_order: Instructions<F>,
    /// 3. Modify Buy Order
    pub buy_modify_order: Instructions<F>,
    /// 4. Buy Aggressive Match
    pub buy_aggressive_match: Instructions<F>,
    /// 5. Buy Passive Match
    pub buy_passive_match: Instructions<F>,
    /// 6. Buy Order Aggressively Matched
    pub buy_aggressive_partial_match: Instructions<F>,
    /// 7. Buy Order Passive Matched
    pub buy_passive_partial_match: Instructions<F>,
    /// Sell Side Instructions
    /// 8. Place Sell Order
    pub sell_insert_order: Instructions<F>,
    /// 9. Cancel Sell Order
    pub sell_delete_order: Instructions<F>,
    /// 10. Modify Sell Order
    pub sell_modify_order: Instructions<F>,
    /// 11. Sell Aggressive Matche
    pub sell_aggressive_match: Instructions<F>,
    /// 12. Sell Passive Match
    pub sell_passive_match: Instructions<F>,
    /// 13. Sell Aggressive Partially Match
    pub sell_aggressive_partial_match: Instructions<F>,
    /// 14. Sell Passive Partially Match
    pub sell_passive_partial_match: Instructions<F>,
    /// All The Instructions sequentially ordered for the Main Trace
    pub instructions: Instructions<F>,
    /// Auxillary Operations that are Looked up by the above instructions
    /// Add Operation for Field Representations of Price, Time
    pub add_operations: Vec<[F; 32]>,
    /// Less Than Operation. Compares Price pairs, comprising 8 Field Elements each
    pub less_than_operations: LessThanOperations,
    /// strict less than operations
    pub strict_less_than_operations: LessThanOperations,
    /// Comparison Operations. Compares two Price, Time pairs
    pub comparison_operations: Vec<[F; 53]>,
    /// Hash Operations For Merklelization.
    pub poseidon_operations: PoseidonOperations,
    /// Uint8 Operations
    pub byte_operations: ByteOperations,
    /// Initial State of the Execution Trace
    pub initial_state: StateFelts<F>,
    /// Final State
    pub final_state: StateFelts<F>,
}

impl Default for ExecutionTrace<BaseField> {
    fn default() -> Self {
        Self::new()
    }
}

impl ExecutionTrace<BaseField> {
    /// Creates a new Execution Trace
    pub fn new() -> Self {
        Self {
            buy_insert_order: Vec::new(),
            buy_delete_order: Vec::new(),
            buy_modify_order: Vec::new(),
            buy_aggressive_match: Vec::new(),
            buy_passive_match: Vec::new(),
            buy_aggressive_partial_match: Vec::new(),
            buy_passive_partial_match: Vec::new(),
            sell_insert_order: Vec::new(),
            sell_delete_order: Vec::new(),
            sell_modify_order: Vec::new(),
            sell_aggressive_match: Vec::new(),
            sell_passive_match: Vec::new(),
            sell_aggressive_partial_match: Vec::new(),
            sell_passive_partial_match: Vec::new(),
            instructions: Vec::new(),
            add_operations: Vec::new(),
            less_than_operations: Vec::new(),
            strict_less_than_operations: Vec::new(),
            comparison_operations: Vec::new(),
            poseidon_operations: Vec::new(),
            byte_operations: array::from_fn(|_| BaseColumn::zeros(1 << 16)),
            initial_state: array::from_fn(|_| BaseField::zero()),
            final_state: array::from_fn(|_| BaseField::zero()),
        }
    }

    /// Adds an instruction to the Execution Trace
    pub fn add_instruction(&mut self, instruction: InstructionFelts<BaseField>) {
        match Opcode::from_field(instruction[InstructionColumn::OPCODE]) {
            Opcode::InsertBuyOrder => self.buy_insert_order.push(instruction),
            Opcode::CancelBuyOrder => self.buy_delete_order.push(instruction),
            Opcode::UpdateBuyOrder => self.buy_modify_order.push(instruction),
            Opcode::MatchAggressiveBuy => self.buy_aggressive_match.push(instruction),
            Opcode::MatchPassiveBuy => self.buy_passive_match.push(instruction),
            Opcode::PartialMatchAggressiveBuy => {
                self.buy_aggressive_partial_match.push(instruction)
            }
            Opcode::PartialMatchPassiveBuy => self.buy_passive_partial_match.push(instruction),
            Opcode::InsertSellOrder => self.sell_insert_order.push(instruction),
            Opcode::CancelSellOrder => self.sell_delete_order.push(instruction),
            Opcode::UpdateSellOrder => self.sell_modify_order.push(instruction),
            Opcode::MatchAggressiveSell => self.sell_aggressive_match.push(instruction),
            Opcode::MatchPassiveSell => self.sell_passive_match.push(instruction),
            Opcode::PartialMatchAggressiveSell => {
                self.sell_aggressive_partial_match.push(instruction)
            }
            Opcode::PartialMatchPassiveSell => self.sell_passive_partial_match.push(instruction),
        }
        self.instructions.push(instruction);
    }

    /// The following methods will take input as an event
    /// and compute the corresponding Trace Row For constraint evaluations
    /// Adds an Add Event to the Execution Trace
    pub fn add_add_event(
        &mut self,
        a: [BaseField; N_U64_LIMBS],
        b: [BaseField; N_U64_LIMBS],
    ) -> Result<(), RangeCheckError> {
        let mut row = [BaseField::zero(); AddColumn::MAIN_COLS];

        let mut carry = [BaseField::zero(); N_U64_LIMBS - 1];
        let mut c = [BaseField::zero(); N_U64_LIMBS];

        for i in 0..7 {
            let sum = a[i]
                + b[i]
                + (if i > 0 {
                    carry[i - 1]
                } else {
                    BaseField::zero()
                });

            if sum > BaseField::from(255) {
                c[i] = sum - BaseField::from(256);
                carry[i] = BaseField::one();
            } else {
                c[i] = sum;
                carry[i] = BaseField::zero();
            }
        }
        // Compute the final limb
        let last_sum = a[7] + b[7] + carry[6];
        c[7] = last_sum;

        // Dispatch range check events in the same order as in constraints.rs
        let values: Vec<BaseField> = chain!(a.into_iter(), b.into_iter(), c.into_iter()).collect();

        // Add range checks for each byte of a, b and c
        for i in (0..24).step_by(4) {
            self.add_range_check_u8_event(values[i].0, values[i + 1].0)?;
            self.add_range_check_u8_event(values[i + 2].0, values[i + 3].0)?;
        }
        // Copy input operands a and b ,computed c and carry values into the row
        row[AddColumn::A..AddColumn::B].copy_from_slice(&a);
        row[AddColumn::B..AddColumn::C].copy_from_slice(&b);
        row[AddColumn::C..AddColumn::CARRY].copy_from_slice(&c);
        row[AddColumn::CARRY..AddColumn::IS_REAL].copy_from_slice(&carry);

        // Mark this as a real operation
        row[AddColumn::IS_REAL] = BaseField::one();

        self.add_operations.push(row);
        Ok(())
    }

    /// Adds a Less Than Event by recording the corresponding Trace Row
    /// Returns an error if any limb in a or b is greater than 255
    pub fn add_strictly_less_than_event(
        &mut self,
        a: [BaseField; N_U64_LIMBS],
        b: [BaseField; N_U64_LIMBS],
    ) -> Result<(), IMTError> {
        self.add_less_than_event_internal(a, b, true)
    }

    /// Adds a Less Than Event by recording the corresponding Trace Row
    /// Returns an error if any limb in a or b is greater than 255
    pub fn add_less_than_event(
        &mut self,
        a: [BaseField; N_U64_LIMBS],
        b: [BaseField; N_U64_LIMBS],
    ) -> Result<(), IMTError> {
        self.add_less_than_event_internal(a, b, false)
    }

    /// Adds a Comparison Event by recording the corresponding Trace Row
    pub fn add_comparison_event(&mut self, event: [BaseField; 53]) {
        self.comparison_operations.push(event);
    }

    /// Adds a Poseidon hash operation for a Merkle tree node
    ///
    /// This hashes two child nodes together, each represented by 8 BaseField elements
    pub fn add_merkle_hash_event(&mut self, a: [BaseField; 8], b: [BaseField; 8]) {
        let mut input = [BaseField::zero(); 17];
        input[0..8].copy_from_slice(&a);
        input[8..16].copy_from_slice(&b);
        input[16] = BaseField::one(); // Selector for Merkle hash operation

        self.poseidon_operations.push(input);
    }

    /// Adds a Poseidon hash operation for a leaf node
    ///
    /// # Arguments
    /// * `leaf_felts` - The field elements representing the leaf data
    pub fn add_leaf_hash_event(&mut self, leaf_felts: &LeafFelts<BaseField>) {
        let mut input = [BaseField::zero(); 17];

        // Only the first 16 elements are used in the hash
        for (i, value) in leaf_felts[0..16].iter().enumerate() {
            input[i] = *value;
        }

        input[16] = BaseField::one(); // Selector for leaf hash operation
        self.poseidon_operations.push(input);
    }

    /// Adds an And U8 Event by recording the corresponding Trace Row
    /// Returns an error if a or b is greater than 255
    pub fn add_and_u8_event(&mut self, a: u32, b: u32) -> Result<(), IMTError> {
        if (a >= 256) || (b >= 256) {
            return Err(IMTError::InvalidU8Pair(a, b));
        }
        let offset = (a << 8) + b;
        self.byte_operations[0].as_mut_slice()[offset as usize].0 += 1;
        Ok(())
    }

    /// Adds a Less Than U8 Event by recording the corresponding Trace Row
    /// Returns an error if a or b is greater than 255
    pub fn add_less_than_u8_event(&mut self, a: u32, b: u32) -> Result<(), IMTError> {
        if a >= 256 || b >= 256 {
            return Err(IMTError::InvalidU8Pair(a, b));
        }
        let offset = (a << 8) + b;
        self.byte_operations[1].as_mut_slice()[offset as usize].0 += 1;
        Ok(())
    }

    /// Adds a Range Check U8 Event by recording the corresponding Trace Row.
    ///
    /// # Errors
    /// Returns a `RangeCheckError::InputLimbExceedsRange` if `a` or `b` is greater than 255.
    pub fn add_range_check_u8_event(&mut self, a: u32, b: u32) -> Result<(), RangeCheckError> {
        if a >= 256 || b >= 256 {
            return Err(RangeCheckError::InputLimbExceedsRange);
        }
        let offset = (a << 8) + b;
        self.byte_operations[2].as_mut_slice()[offset as usize].0 += 1;
        Ok(())
    }

    /// Max Log Size for the Execution Trace
    pub fn max_log_size(&self) -> u32 {
        let n = max([
            self.buy_insert_order.len(),
            self.buy_delete_order.len(),
            self.buy_modify_order.len(),
            self.buy_aggressive_match.len(),
            self.buy_passive_match.len(),
            self.buy_aggressive_partial_match.len(),
            self.buy_passive_partial_match.len(),
            self.sell_insert_order.len(),
            self.sell_delete_order.len(),
            self.sell_modify_order.len(),
            self.sell_aggressive_match.len(),
            self.sell_passive_match.len(),
            self.sell_aggressive_partial_match.len(),
            self.sell_passive_partial_match.len(),
            self.instructions.len(),
            self.add_operations.len(),
            self.less_than_operations.len(),
            self.strict_less_than_operations.len(),
            self.comparison_operations.len(),
            self.poseidon_operations.len() / N_INSTANCES_PER_ROW,
            1 << (2 * N_U64_FELTS), // 2^8 * 2^8 combinations
        ])
        .unwrap();
        
        (n - 1).ilog2() + 1
    }

    /// Returns the log size for a given Component
    pub fn log_size(&self, component: VexComponent) -> u32 {
        let len = match component {
            VexComponent::InsertBuyOrder => self.buy_insert_order.len(),
            VexComponent::CancelBuyOrder => self.buy_delete_order.len(),
            VexComponent::UpdateBuyOrder => self.buy_modify_order.len(),
            VexComponent::MatchAggressiveBuy => self.buy_aggressive_match.len(),
            VexComponent::MatchPassiveBuy => self.buy_passive_match.len(),
            VexComponent::PartialMatchAggressiveBuy => self.buy_aggressive_partial_match.len(),
            VexComponent::PartialMatchPassiveBuy => self.buy_passive_partial_match.len(),
            VexComponent::InsertSellOrder => self.sell_insert_order.len(),
            VexComponent::CancelSellOrder => self.sell_delete_order.len(),
            VexComponent::UpdateSellOrder => self.sell_modify_order.len(),
            VexComponent::MatchAggressiveSell => self.sell_aggressive_match.len(),
            VexComponent::MatchPassiveSell => self.sell_passive_match.len(),
            VexComponent::PartialMatchAggressiveSell => self.sell_aggressive_partial_match.len(),
            VexComponent::PartialMatchPassiveSell => self.sell_passive_partial_match.len(),
            VexComponent::Processor => self.instructions.len(),
            VexComponent::Addition => self.add_operations.len(),
            VexComponent::LessThan => self.less_than_operations.len(),
            VexComponent::StrictLessThan => self.strict_less_than_operations.len(),
            VexComponent::Poseidon => self.poseidon_operations.len() / N_INSTANCES_PER_ROW,
            VexComponent::Bytes => 1 << N_U64_FELTS, // 2^8 * 2^8 combinations
        };
        (len.max(16) - 1).ilog2() + 1
    }

    /// Adds a Less Than Event by recording the corresponding Trace Row
    /// the strict flag is used to determine if the comparison is strict
    /// # Returns
    ///  - Ok(()) if the operation is successful
    ///  - InvalidU8Pair(a, b) if a or b is greater than 255
    fn add_less_than_event_internal(
        &mut self,
        a: [BaseField; N_U64_LIMBS],
        b: [BaseField; N_U64_LIMBS],
        is_strict: bool,
    ) -> Result<(), IMTError> {
        let mut row = [BaseField::zero(); LessThanColumn::IS_REAL + 1];
        row[LessThanColumn::A..LessThanColumn::B].copy_from_slice(&a);
        row[LessThanColumn::B..LessThanColumn::C].copy_from_slice(&b);

        let flags = &mut row[LessThanColumn::FLAGS..LessThanColumn::A_COMPARISON_BYTE];
        let mut c = BaseField::zero();
        let mut a_cmp = BaseField::zero();
        let mut b_cmp = BaseField::zero();

        for (a_byte, b_byte, flag) in izip!(a.iter().rev(), b.iter().rev(), flags.iter_mut().rev())
        {
            if a_byte.0 > 255 || b_byte.0 > 255 {
                return Err(IMTError::InvalidU8Pair(a_byte.0, b_byte.0));
            }
            match a_byte.cmp(b_byte) {
                std::cmp::Ordering::Less => {
                    *flag = BaseField::one();
                    a_cmp = *a_byte;
                    b_cmp = *b_byte;
                    c = BaseField::one();
                    break;
                }
                std::cmp::Ordering::Greater => {
                    *flag = BaseField::one();
                    a_cmp = *a_byte;
                    b_cmp = *b_byte;
                    break;
                }
                _ => {}
            }
        }

        // less_than_u8 events for a_cmp and b_cmp bytes
        self.add_less_than_u8_event(a_cmp.0, b_cmp.0)?;
        row[LessThanColumn::A_COMPARISON_BYTE] = a_cmp;
        row[LessThanColumn::B_COMPARISON_BYTE] = b_cmp;
        row[LessThanColumn::IS_REAL] = BaseField::one();

        if is_strict {
            row[LessThanColumn::C] = c;
            self.strict_less_than_operations.push(row);
        } else {
            // returns 1 as result if a = b, else returns c
            row[LessThanColumn::C] = if a == b { BaseField::one() } else { c };
            self.less_than_operations.push(row);
        }

        Ok(())
    }
}

/// Execution Trace Shape
/// Used For Debugging and Logging
/// Can be created from Execution`` Trace
/// Can contain log sizes or sizes
/// Example:
/// ```
/// use vex_prover::executor::record::ExecutionTrace;
///
/// let trace = ExecutionTrace::new();
/// let shape = trace.sizes();
/// ```
#[derive(Debug)]
pub struct ExecutionTraceShape<T: Copy> {
    pub buy_insert_order: T,
    pub buy_delete_order: T,
    pub buy_modify_order: T,
    pub buy_aggressive_match: T,
    pub buy_passive_match: T,
    pub buy_aggressive_partial_match: T,
    pub buy_passive_partial_match: T,
    pub sell_insert_order: T,
    pub sell_delete_order: T,
    pub sell_modify_order: T,
    pub sell_aggressive_match: T,
    pub sell_passive_match: T,
    pub sell_aggressive_partial_match: T,
    pub sell_passive_partial_match: T,
    pub instructions: T,
    pub add_operations: T,
    pub less_than_operations: T,
    pub strict_less_than_operations: T,
    pub comparison_operations: T,
    pub poseidon_operations: T,
}

impl<F> ExecutionTrace<F> {
    pub fn sizes(&self) -> ExecutionTraceShape<usize> {
        ExecutionTraceShape {
            buy_insert_order: self.buy_insert_order.len(),
            buy_delete_order: self.buy_delete_order.len(),
            buy_modify_order: self.buy_modify_order.len(),
            buy_aggressive_match: self.buy_aggressive_match.len(),
            buy_passive_match: self.buy_passive_match.len(),
            buy_aggressive_partial_match: self.buy_aggressive_partial_match.len(),
            buy_passive_partial_match: self.buy_passive_partial_match.len(),
            sell_insert_order: self.sell_insert_order.len(),
            sell_delete_order: self.sell_delete_order.len(),
            sell_modify_order: self.sell_modify_order.len(),
            sell_aggressive_match: self.sell_aggressive_match.len(),
            sell_passive_match: self.sell_passive_match.len(),
            sell_aggressive_partial_match: self.sell_aggressive_partial_match.len(),
            sell_passive_partial_match: self.sell_passive_partial_match.len(),
            instructions: self.instructions.len(),
            add_operations: self.add_operations.len(),
            less_than_operations: self.less_than_operations.len(),
            strict_less_than_operations: self.strict_less_than_operations.len(),
            comparison_operations: self.comparison_operations.len(),
            poseidon_operations: self.poseidon_operations.len(),
        }
    }
}
